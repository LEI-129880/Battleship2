package battleship;

/** Demonstracao temporaria de Long Method para a ficha 3; nao e usada pelo jogo. */
public final class LongMethodDemo129890 {
    private LongMethodDemo129890() {
    }

    public static int sumOneToThirtyFive() {
        int total = 0;
        for (int number = 1; number <= 35; number++) {
            total += number;
        }
        return total;
    }
}
